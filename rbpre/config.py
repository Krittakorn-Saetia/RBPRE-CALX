"""rbpre.config: endpoints and local credentials of the off-chain services.

Passwords are read from infra/.env (generated by infra/services.sh, never
committed); environment variables of the same name override them.
"""

from __future__ import annotations

import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = Path(os.environ.get("RBPRE_ENV_FILE", ROOT / "infra" / ".env"))


def _load() -> dict[str, str]:
    vals: dict[str, str] = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                vals[k.strip()] = v.strip()
    vals.update({k: v for k, v in os.environ.items() if k in vals or k.startswith(("NEO4J_", "REDIS_", "MINIO_"))})
    return vals


_ENV = _load()

NEO4J_URI = _ENV.get("NEO4J_URI", "bolt://127.0.0.1:7687")
NEO4J_USER = _ENV.get("NEO4J_USER", "neo4j")
NEO4J_PASSWORD = _ENV.get("NEO4J_PASSWORD", "")

REDIS_HOST = _ENV.get("REDIS_HOST", "127.0.0.1")
REDIS_PORT = int(_ENV.get("REDIS_PORT", "6379"))
REDIS_PASSWORD = _ENV.get("REDIS_PASSWORD", "")

MINIO_ENDPOINT = _ENV.get("MINIO_ENDPOINT", "127.0.0.1:9000")
MINIO_USER = _ENV.get("MINIO_USER", "rbpre")
MINIO_PASSWORD = _ENV.get("MINIO_PASSWORD", "")
MINIO_BUCKET = _ENV.get("MINIO_BUCKET", "ehr")
